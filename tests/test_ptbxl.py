class TestRecordPath:
    def test_resolves_both_resolutions(self, dataset_root: Path, metadata: pd.DataFrame) -> None:
        layout = resolve_layout(dataset_root)
        row = metadata.loc[1]
        assert record_path(layout, row, 100).name == "00001_lr"
        assert record_path(layout, row, 500).name == "00001_hr"
        assert record_path(layout, row, 500).is_relative_to(dataset_root)

    def test_rejects_other_rates(self, dataset_root: Path, metadata: pd.DataFrame) -> None:
        layout = resolve_layout(dataset_root)
        with pytest.raises(ValueError, match="must be 100 or 500"):
            record_path(layout, metadata.loc[1], 250)  # type: ignore[arg-type]
