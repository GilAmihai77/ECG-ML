class TestParseScpCodes:
    def test_parses_stringified_dict(self) -> None:
        assert parse_scp_codes("{'NORM': 100.0, 'SR': 0.0}") == {"NORM": 100.0, "SR": 0.0}

    def test_passes_through_mapping(self) -> None:
        assert parse_scp_codes({"IMI": 80}) == {"IMI": 80.0}

    def test_empty_and_missing_become_empty_dict(self) -> None:
        assert parse_scp_codes("") == {}
        assert parse_scp_codes(float("nan")) == {}

    def test_non_dict_payload_is_rejected(self) -> None:
        with pytest.raises(ValueError, match="did not parse to a dict"):
            parse_scp_codes("['NORM']")


class TestAssignSuperclasses:
    mapping = {"NORM": "NORM", "IMI": "MI", "LVH": "HYP", "NDT": "STTC"}

    def test_returns_canonical_order(self) -> None:
        # Input order is HYP before MI; output must follow SUPERCLASSES order.
        result = assign_superclasses({"LVH": 100.0, "IMI": 100.0}, self.mapping)
        assert result == ["MI", "HYP"]

    def test_zero_likelihood_is_still_asserted(self) -> None:
        """0.0 means 'asserted, confidence unquantified', not 'absent'."""
        assert assign_superclasses({"IMI": 0.0}, self.mapping) == ["MI"]

    def test_threshold_filters_low_confidence(self) -> None:
        codes = {"IMI": 80.0, "LVH": 15.0}
        assert assign_superclasses(codes, self.mapping, likelihood_threshold=50.0) == ["MI"]

    def test_non_diagnostic_statements_ignored(self) -> None:
        assert assign_superclasses({"SR": 100.0, "AFIB": 100.0}, self.mapping) == []

    def test_duplicate_superclass_collapses(self) -> None:
        mapping = {"IMI": "MI", "ASMI": "MI"}
        assert assign_superclasses({"IMI": 100.0, "ASMI": 100.0}, mapping) == ["MI"]


class TestSplitOfFold:
    @pytest.mark.parametrize("fold", [1, 2, 3, 4, 5, 6, 7, 8])
    def test_training_folds(self, fold: int) -> None:
        assert split_of_fold(fold) == "train"

    def test_validation_and_test_folds(self) -> None:
        assert split_of_fold(9) == "val"
        assert split_of_fold(10) == "test"

    @pytest.mark.parametrize("fold", [0, 11, -1])
    def test_out_of_range_rejected(self, fold: int) -> None:
        with pytest.raises(ValueError, match="Unexpected strat_fold"):
            split_of_fold(fold)


class TestLoadMetadata:
    def test_adds_superclass_columns(self, metadata: pd.DataFrame) -> None:
        for name in SUPERCLASSES:
            assert name in metadata.columns
        assert metadata.loc[1, "superclasses"] == ["NORM"]
        assert metadata.loc[2, "superclasses"] == ["MI", "HYP"]
        assert metadata.loc[4, "superclasses"] == ["MI", "CD"]

    def test_unlabelled_records_are_retained_and_flagged(
        self, metadata: pd.DataFrame
    ) -> None:
        """Records with no diagnostic statement must survive loading."""
        assert 5 in metadata.index
        assert metadata.loc[5, "superclasses"] == []
        assert metadata.loc[5, "n_superclasses"] == 0

    def test_split_column_follows_published_folds(self, metadata: pd.DataFrame) -> None:
        assert metadata.loc[1, "split"] == "train"
        assert metadata.loc[3, "split"] == "val"
        assert metadata.loc[5, "split"] == "test"

    def test_age_sentinel_flagged(self, metadata: pd.DataFrame) -> None:
        assert metadata.loc[3, "age"] == AGE_SENTINEL
        assert bool(metadata.loc[3, "age_censored"]) is True
        assert bool(metadata.loc[1, "age_censored"]) is False

    def test_accepts_plain_path(self, dataset_root: Path) -> None:
        assert len(load_metadata(str(dataset_root))) == 5

    def test_threshold_is_applied(self, dataset_root: Path) -> None:
        strict = load_metadata(dataset_root, likelihood_threshold=50.0)
        # LVH at likelihood 15.0 drops out; IMI at 80.0 survives.
        assert strict.loc[2, "superclasses"] == ["MI"]

    def test_label_matrix_shape_and_order(self, metadata: pd.DataFrame) -> None:
        matrix = label_matrix(metadata)
        assert matrix.shape == (5, len(SUPERCLASSES))
        assert matrix[0].tolist() == [True, False, False, False, False]


class TestPatientLeakage:
    def test_clean_split_reports_nothing(self, metadata: pd.DataFrame) -> None:
        assert check_patient_fold_disjoint(metadata).empty

    def test_detects_patient_spanning_folds(self, metadata: pd.DataFrame) -> None:
        leaked = metadata.copy()
        leaked.loc[5, "patient_id"] = 101  # same patient as fold-1 record 1
        offenders = check_patient_fold_disjoint(leaked)
        assert list(offenders.index) == [101]
        assert offenders.loc[101, "folds"] == [1, 10]
        assert offenders.loc[101, "n_records"] == 2


