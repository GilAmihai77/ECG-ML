class TestCooccurrence:
    def test_diagonal_is_class_count(self, metadata: pd.DataFrame) -> None:
        table = cooccurrence_matrix(metadata)
        assert table.loc["MI", "MI"] == 2
        assert table.loc["NORM", "NORM"] == 1

    def test_off_diagonal_counts_pairs(self, metadata: pd.DataFrame) -> None:
        table = cooccurrence_matrix(metadata)
        assert table.loc["MI", "HYP"] == 1
        assert table.loc["HYP", "MI"] == 1
        assert table.loc["NORM", "MI"] == 0

    def test_normalised_rows_are_conditional(self, metadata: pd.DataFrame) -> None:
        table = cooccurrence_matrix(metadata, normalise=True)
        assert table.loc["MI", "MI"] == 1.0
        assert table.loc["MI", "HYP"] == 0.5  # 1 of the 2 MI records also has HYP


class TestAnnotationProvenance:
    def test_handles_mixed_boolean_encodings(self, metadata: pd.DataFrame) -> None:
        """Row 3 encodes its flags as 0.0/1.0 rather than False/True."""
        stats = annotation_provenance(metadata)
        assert stats.total == 5
        assert stats.machine_generated == 3  # rows 1, 4, 5
        assert stats.human_validated == 3  # rows 2, 3, 4
        assert stats.second_opinion == 1  # row 2

    def test_machine_only_and_human_only(self, metadata: pd.DataFrame) -> None:
        stats = annotation_provenance(metadata)
        assert stats.machine_only == 2  # rows 1 and 5: autogenerated, never checked
        assert stats.human_only == 2  # rows 2 and 3: human, not autogenerated

    def test_counts_distinct_validators(self, metadata: pd.DataFrame) -> None:
        assert annotation_provenance(metadata).n_validators == 2  # 3.0 and 5.0

    def test_as_series_includes_percentages(self, metadata: pd.DataFrame) -> None:
        series = annotation_provenance(metadata).as_series()
        assert "40.0%" in series["machine-only (never human-checked)"]

    def test_missing_columns_raise(self, metadata: pd.DataFrame) -> None:
        with pytest.raises(KeyError, match="second_opinion"):
            annotation_provenance(metadata.drop(columns=["second_opinion"]))

    def test_per_fold_breakdown(self, metadata: pd.DataFrame) -> None:
        table = provenance_by_fold(metadata)
